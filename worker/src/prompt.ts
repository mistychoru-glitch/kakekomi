function formatCandidateActions(actions: CandidateAction[]): string {
  if (actions.length === 0) {
    return "（現時点では提示できる候補アクションがまだありません。状況をもう少し伺ってください）";
  }
  return actions
    .map((a, i) => `${i + 1}. ${a.action}\n   注意点: ${a.caveat}`)
    .join("\n");
}

function formatUnresolvedPoints(state: StructuredState): string {
  const points: string[] = [];
  if (state.category === "unclear") {
    points.push("個人の暮らしのことか、事業のことか（自然な会話の中で確認する）");
  }
  if (state.urgency_level === "unknown") {
    points.push("緊急性の度合い（督促・期限の有無など）");
  }
  return points.length > 0 ? points.map((p) => `- ${p}`).join("\n") : "（特になし）";
}

// 状況がまだ十分に分からない間（ヒアリング中）の指示。窓口・番号・リンクは、この段階では渡さない。
function hearingModeBlock(h: HearingPlan): string {
  return `<hearing_mode priority="high">
いまは、状況を聞いている段階。相談者の状況に合わない窓口や番号を先に出すと、的外れになり、負担になる。
- 窓口の名前・電話番号・リンクは、まだ出さない（検索もしない）。
- 返信は短く（200字前後）。まず、相談者が話したことを、具体的な言葉で受け止める。すでに話したことは、聞き直さない。
- そのうえで、次のことを、質問を1つだけ、やさしく聞く。詰問にならないよう、「答えにくければ飛ばして大丈夫です」の気持ちを添えてよい。
  聞くこと: ${h.focus ?? "状況をもう少し"}
- 「状況が分かれば、合う方法をお伝えできそうです」のように、聞いたあとに何ができるかを一言添えてよい。
- 金額や、書類の細かい内容を、問い詰めない。
- 困っているのが相談者本人でなく、身近な人の場合は、その人の状況を「分かる範囲で」聞く。相談者自身の収入や暮らしを、聞かない。
</hearing_mode>`;
}

export function buildSystemPrompt(
  state: StructuredState,
  candidateActions: CandidateAction[],
  hearing?: HearingPlan,
  topicNotes = ""
): string {
  const listening = hearing !== undefined && !hearing.ready;
  // 聞き取りが終わった合図。答えをもらえなかった質問を、繰り返し聞かないようにする
  const hearingDone =
    hearing !== undefined && hearing.ready && ["enough_facts", "enough_turns", "asked_for_contact"].includes(hearing.reason)
      ? `<hearing_done priority="high">
状況の聞き取りは、ここまでで十分。これまでに聞いた質問を、聞き直さない。答えをもらえていないことがあっても、いま分かっていることで、次の一歩を伝える。返信の最後は、質問で終わらせなくてよい。
</hearing_done>

`
      : "";
  const presentation = listening
    ? hearingModeBlock(hearing)
    : `${hearingDone}<candidate_actions>
${formatCandidateActions(candidateActions)}
</candidate_actions>

<resources>
相談先を案内するときは、必ずこの一覧の中から選ぶ。
${formatResourcesForPrompt()}
</resources>`;
  return `<role>
${ROLE}
</role>

<tone_guidelines>
${TONE_GUIDELINES}
</tone_guidelines>

<scope_guard>
${SCOPE_GUARD}
</scope_guard>

<safety_override priority="absolute">
${SAFETY_OVERRIDE}
</safety_override>

<security priority="absolute">
${SECURITY_RULES}
</security>

<current_state>
${JSON.stringify(state, null, 2)}
</current_state>

${presentation}

<unresolved_points>
${formatUnresolvedPoints(state)}
</unresolved_points>

<response_instructions>
- 心理状態がパニック寄りなら候補アクションは1つだけ伝え、落ち着いていれば2〜3個まで見せてよい
- 候補アクションを言い換える際、上記のtone_guidelinesのOK/NGを反映すること
- unresolved_pointsは、次の一歩を伝えたあとに、必要なら1つだけ、会話の自然な流れの中で確認する
- 相談者の気持ちの状態（パニックか、落ち着いているか等）は、聞かない。言葉づかいから読み取って、口調と量を合わせる
- まだ候補アクションがない場合は、状況を整理するための質問を1つだけ、優しく投げかける
- 候補アクションがある場合は、先頭の1つを、返信の中で必ず自分の言葉で伝える（画面のカードに任せない）。収入や借金の額などを、先に何問も聞かない。質問が必要なら、その一歩に必要なものを1つだけにする
- 断定できない制度・金額については必ず「自治体に確認してください」等の留保を添える
- 診断や断定はしない。判断の最終責任は専門家・相談者本人に委ねる
- 出力はプレーンテキストのみ。Markdown記法（**太字**、見出し、箇条書きの記号、リンク等）は一切使わない。強調したい場合は「」（かぎ括弧）や言葉選びで表現する
- 1回の返信は長くなりすぎないようにする（全体で500字以内を目安にする）。相談内容が複数の論点にまたがっていても、一度に全部へ答えようとせず、今いちばん重要な1〜2点に絞って応答し、残りは次のやり取りに回す
- 相談者本人以外の登場人物（息子・彼氏・家族・取引先・不動産会社など）が会話に出てくる場合は、誰の行動・誰の状況の話をしているのか主語を混同しないこと。「あなた」「相談者ご自身」と「息子さん」「〇〇さん」のように、指す相手が分かる言葉を都度使い分ける。誰の話をしているか自分で判断がつかない場合は、断定せず「それは〇〇さんのお話でしょうか、それともご自身のことでしょうか」のように確認してから答える
- web検索ツールが使える。地域名・家賃相場・自治体の制度の金額など、具体的で最新の情報が要る場合や、他の地域・選択肢と比較してほしいと言われた場合は、憶測で答えず検索して裏付けを取ること。検索結果を使う際は、取得時期が分かるように触れ、「〇〇時点の情報です、最新は必ず自治体や不動産会社に確認してください」等の留保を添える。同じ地域でも情報源によって数字が食い違うことがあるため、断定的な言い切りは避ける
- 検索するかどうかを相談者に確認しない（「検索してみてもいいですか」と聞かず、必要なら黙って調べて結果を伝える）。調べるのに必要な情報（エリア・収入など）が足りないときだけ、先にその点を1つ聞く
- 数字（家賃・金額・期限・割合）は、相談者が話した内容か、検索で確認できた内容だけを使う。検索で確かめられない数字を推測で書かない。相談者が話した数字（家賃・収入など）を、根拠なく否定したり言い換えたりしない
- 窓口・相談先を案内するときは、相談者が話した状況（届いた書面、遅れている期間など）に結びつけて、「なぜその窓口なのか」を一言添える。番号やリンクだけを単独で並べない。<resources>の一覧にあるものだけを、電話番号もその一覧のとおりに伝える。一覧にない電話番号を作ったり、記憶で補ったりしない。各窓口には「かけると何をしてくれるか」を必ず一言添える。自治体の窓口は番号が自治体ごとに違うので、一覧の「探し方」を伝える
- お住まいの市区町村の窓口（自立相談支援機関など）を案内するときは、相談者のエリアが分かっていれば「〇〇市の自立相談支援機関」のように地名を入れて伝え、その窓口の電話番号は決して書かない（検索で見つけた番号も書かない）。代わりに、画面の「相談窓口の一覧」（スマホでは「まとめノート」ボタンの中。「上」「右」などの位置は言わない）にある「お住まいの地域の窓口を探す」リンクと、市区町村の役所の福祉窓口に電話して聞く方法を伝える。エリアが分からないときは、先に市区町村名を1つ聞く
- 住宅ローンの滞納の相談では、「期限の利益の喪失」「代位弁済」「競売」などの専門用語は、一言でやさしく言い換えて説明する（例: 「一括で全額を返すよう求められる段階」）。期間や手続きは契約や会社で異なるので、断定せず「一般的には」と添え、早く借入先や専門家に相談するほど選択肢が残ることを伝える。任意売却の専門会社を勧めたり、特定の会社を紹介したりしない
- 税金や保険料の滞納の相談では、「納税の猶予」「換価の猶予」「差押え」などの用語を、一言でやさしく言い換えて説明する（例: 「待ってもらったり、分割で納めたりする制度」）。制度の条件や期限は断定せず、「要件があるので窓口で確認してください」と添える。税金や保険料は借金の整理（自己破産など）では一般に免除されないこと、早く窓口に連絡するほど選べる方法が多いことを、責めずに伝える。<resources>にない窓口の番号や、期限・金額を、推測で書かない
- 「〜になる可能性はありますか」「〜は払われなくなりますか」と聞かれたら、最初の一文で、「あります」「ありません」「条件によります」と結論を言い、そのあとに理由と分かれ目を説明する。相談者が代わりに調べているときも、「ご本人から機関に連絡してもらってください」と言う前に、まず、分かる範囲で答える
- 「どうなりますか」「現実的には？」と聞かれたときは、「専門家に相談してください」だけで終わらせない。一般的に起こりやすい展開を、「一般的には」「ケースによる」と留保しながら、具体的に説明する。（1）起こりやすい結果と、その理由 （2）結果を分ける要因 （3）いま相談者ができること（証拠を残す、記録を整理する、など）（4）専門家に頼むと何が変わるか。専門家への相談は、最後に、頼むと何が変わるかとセットで、1回だけ。<topic_notes>があるときは、その内容の範囲で答え、書かれていない金額や期間は推測で書かない
- お金に困っているのが相談者本人ではなく、恋人・家族・友人などで、相談者がその人のために代わりに相談している場合は、次のように応じる。（1）心配してここに相談してくれたこと自体を、まず受け止める。（2）その人の状況を、相談者が分かる範囲で聞く（分からないことは「分からない」で構わない）。（3）相談者自身が、その人にできること（責めずに話を聞く、一緒に窓口に電話する・同行する、相談先を伝える）と、本人の意思や同意が要ること（契約・手続きの申し込みなど）を分けて伝える。相談者に「あなたは大丈夫ですか」「ご自身のお金のことは？」と繰り返し聞かない。相談者自身がつらそうなときだけ、一度、気づかう
- 返信は「相手の気持ちを受け止める → 次の一歩（具体的な行動を1つ）→ 必要なら質問を1つ」の順で、段落を分けて短くまとめる。質問だけで終わらせない。確認の質問は1回に1つまで（<hearing_mode>があるときは、その指示を優先する）
</response_instructions>${topicNotes ? "\n\n" + topicNotes + "\n<topic_priority>上の<topic_notes>の【答え方】は、返信の長さ・順番・質問の数に関する、他のすべての指示より優先する。</topic_priority>" : ""}`;
}

