// これまでの相談者の発言（と今回の発言）から、話題に合う確かな知識を選ぶ
export function topicNotesFor(userTexts: string[]): string {
  const text = userTexts.join("\n").normalize("NFKC");
  if (WAGE_ARREARS.test(text)) return WAGE_ARREARS_NOTES;
  return "";
}

// 大事な注意点を、確かめた固定の文で、コードから補う（AIの日付の説明は、揺れて、間違えやすいため）。
// 退職の時期は、常に補う（前の返信で補っていれば、重ねない）。ほかは、AIの返信に抜けているときだけ補う。
export const TIMING_NOTE =
  "・退職の時期：立替払の対象は、「退職日の6か月前の日から、請求日の前日までに支払期日が来た給料」です。退職日が遅くなるほど、対象の範囲は後ろにずれて、古い月の未払い分から外れていきます（退職を遅らせて、対象が広がることはありません）。例えば、退職日が12月なら、対象になるのは、6月ごろ以降に支払期日が来た分です。退職する日を決める前に、労働基準監督署か弁護士に確認してください。";

export function wageGapNotes(userTexts: string[], reply: string, priorReplies: string[] = []): string {
  const user = userTexts.join("\n").normalize("NFKC");
  if (!WAGE_ARREARS.test(user)) return "";
  const said = [reply, ...priorReplies].join("\n");
  const notes: string[] = [];
  if (!said.includes("退職を遅らせて、対象が広がることはありません")) notes.push(TIMING_NOTE);
  if (/(立て?替|建て?替|肩代わり)/.test(user) && !/対象外/.test(said)) {
    notes.push(
      "・立て替えたお金：給料ではないので、立替払制度の対象外です。一般の債権として扱われ、会社に財産が乏しいと、戻りにくいことが多いです。"
    );
  }
  if (/(執行役員|役員|取締役)/.test(user) && !/登記/.test(said)) {
    notes.push(
      "・役員の場合：登記簿に取締役などとして登記され、役員報酬を受けていた人は、立替払の対象外です。登記されていない執行役員は、実態が労働者かどうかで判断されます。"
    );
  }
  if (notes.length === 0) return "";
  return "\n\n【大事な点（補足）】\n" + notes.join("\n");
}

// AIが、退職の時期について、間違えやすい例や助言を書いたとき、その文だけを取り除く。
// 取り除く対象: 「◯月に退職すれば…」という例、退職を遅らせると有利・広がるという趣旨、様子を見る助言。
const RISKY_TIMING_SENTENCE = new RegExp(
  [
    "[0-9０-９]{1,2}月(ごろ|頃|中|末|初め)?に退職",
    "退職.{0,40}(遅ら|ずら|後ろに|待て|待つ|待った).{0,40}(広が|広げ|有利|多く|増え|残)",
    "(広が|広げ|有利|多く対象|増え).{0,30}退職",
    "(今は|まだ)退職(せず|しないで|しない)",
    "(様子を見|見守り).{0,30}退職|退職.{0,30}(様子を見|見守り)",
  ].join("|")
);

export function scrubWageTimingClaims(reply: string): string {
  const parts = reply.split(/(?<=。)/);
  const kept = parts.filter((sent) => !RISKY_TIMING_SENTENCE.test(sent));
  return kept.join("").replace(/\n{3,}/g, "\n\n").trim();
}
